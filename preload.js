const { contextBridge, ipcRenderer } = require('electron');

const on = (ch) => (cb) => ipcRenderer.on(ch, (_e, data) => cb(data));
contextBridge.exposeInMainWorld('islet', {
  onMedia: on('media'),
  onAlert: on('alert'),
  onClaude: on('claude'),
  onPermission: on('permission'),
  onSettings: on('settings'),
  onCalendar: on('calendar'),
  onNotifs: on('notifs'),
  onClips: on('clips'),
  onDragEnd: on('drag-end'),
  onLive: on('live'),
  onSummary: on('summary'),
  onTogglePin: on('toggle-pin'),
  onSpotifyChanged: on('spotify-changed'),

  setHover: (over) => ipcRenderer.send('hover', over),
  setFocusable: (on) => ipcRenderer.send('focusable', on),
  mediaCmd: (cmd) => ipcRenderer.send('media-cmd', cmd),
  decide: (id, decision) => ipcRenderer.send('decide', { id, decision }),
  updateSettings: (patch) => ipcRenderer.send('settings-update', patch),
  refreshCalendar: () => ipcRenderer.send('calendar-refresh'),
  openJoin: (url) => ipcRenderer.send('open-join', url),
  copyClip: (id) => ipcRenderer.send('clip-copy', id),
  clearClips: () => ipcRenderer.send('clip-clear'),
  dragClip: (id) => ipcRenderer.send('clip-drag', id),
  getFootball: (league) => ipcRenderer.invoke('football-get', league),
  getF1: () => ipcRenderer.invoke('f1-get'),
  claudeStatus: () => ipcRenderer.invoke('claude-status'),
  claudeConnect: () => ipcRenderer.invoke('claude-connect'),
  claudeDisconnect: () => ipcRenderer.invoke('claude-disconnect'),
  spotifyStatus: () => ipcRenderer.invoke('spotify-status'),
  spotifyConnect: () => ipcRenderer.invoke('spotify-connect'),
  spotifyDisconnect: () => ipcRenderer.invoke('spotify-disconnect'),
  spotifyState: () => ipcRenderer.invoke('spotify-state'),
  spotifyCmd: (cmd, arg) => ipcRenderer.invoke('spotify-cmd', cmd, arg),
  spotifyPlaylists: () => ipcRenderer.invoke('spotify-playlists'),
  spotifyDevices: () => ipcRenderer.invoke('spotify-devices'),
  openLink: (url) => ipcRenderer.send('open-link', url),
  openOnboarding: () => ipcRenderer.send('onboarding-open'),
  onboardingDone: () => ipcRenderer.send('onboarding-done'),
  closeWindow: () => ipcRenderer.send('window-close'),
  loadNote: () => ipcRenderer.invoke('note-load'),
  saveNote: (text) => ipcRenderer.invoke('note-save', text),
});
